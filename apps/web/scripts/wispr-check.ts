/* ============================================================================
 * pnpm wispr:check [options]
 *
 * First-run verification of the Wispr Flow integration, the moment a key exists. It uses the same code path as the
 * browser: the Synapse server mints the client token (so the server's token request is checked too), the real
 * WisprStreamer streams one synthetic utterance over the real client_ws (or REST), and every assumption in
 * apps/web/src/audio/README.md that can be tested from Node is reported as PASS / FAIL / UNKNOWN with evidence.
 *
 *   1. put WISPR_API_KEY=... and WISPR_MODE=client in .env, start the server:  pnpm dev:server
 *      (WISPR_MODE=local checks the ON-DEVICE engine instead: real Whisper on this machine, no key, nothing leaves it)
 *   2. pnpm wispr:check            (about 15 s; speaks a sentence with the Windows voice, nothing is recorded)
 *
 * Options
 *   --server ws://127.0.0.1:8787/ws   Synapse server (default). From another machine add --code <pairing code>
 *   --text "..."                      what the synthetic voice says
 *   --wav file.wav                    use your own 16 kHz mono recording instead (stays on this machine, sent only to Wispr)
 *   --rest                            test the REST fallback instead of the WebSocket
 *   --packets wav                     send per-packet RIFF headers (escape hatch if raw PCM is rejected)
 *   --silence                         also send 1.5 s of silence
 *   --idle 60                         keep an authenticated socket idle for 60 s first (idle-timeout test)
 *   --origin http://localhost:5173    Origin header to send (default: the Vite dev origin, like a browser)
 *   --pace 2                          stream twice as fast as real time (0 = as fast as possible)
 *
 * The audio is a synthetic voice generated by Windows (SAPI) into a temporary file that is deleted right after reading.
 * ========================================================================== */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { randomBytes } from "node:crypto";
import type { WisprTokenInfo } from "../src/audio/types";
import type { WsFactory, WsLike } from "../src/audio/wispr";
import { renderReport, runWisprCheck } from "./wispr-check-lib";

interface Args {
  server: string;
  text: string;
  wav?: string;
  rest: boolean;
  packets: "pcm16" | "wav";
  silence: boolean;
  idle: number;
  origin: string;
  pace: number;
  code?: string;
  language: string[];
}

function parseArgs(argv: string[]): Args {
  const get = (k: string): string | undefined => {
    const i = argv.indexOf(`--${k}`);
    return i >= 0 ? argv[i + 1] : undefined;
  };
  const has = (k: string): boolean => argv.includes(`--${k}`);
  return {
    server: get("server") ?? "ws://127.0.0.1:8787/ws",
    text: get("text") ?? "Hello Synapse. Remind me to email the team about the delay, and ask Sarah about the OAuth two decision.",
    ...(get("wav") ? { wav: get("wav") as string } : {}),
    rest: has("rest"),
    packets: get("packets") === "wav" ? "wav" : "pcm16",
    silence: has("silence"),
    idle: Number(get("idle") ?? 0) || 0,
    origin: get("origin") ?? "http://localhost:5173",
    pace: get("pace") !== undefined ? Number(get("pace")) : 1,
    ...(get("code") ? { code: get("code") as string } : {}),
    language: (get("lang") ?? "").split(",").map((s) => s.trim()).filter(Boolean),
  };
}

/** speak `text` with the Windows voice into a 16 kHz mono WAV and return its PCM; null when SAPI is unavailable */
function synthesize(text: string): Int16Array | null {
  if (process.platform !== "win32") return null;
  const out = path.join(os.tmpdir(), `synapse-check-${randomBytes(4).toString("hex")}.wav`);
  const script = [
    "Add-Type -AssemblyName System.Speech",
    "$s = New-Object System.Speech.Synthesis.SpeechSynthesizer",
    "$f = New-Object System.Speech.AudioFormat.SpeechAudioFormatInfo(16000, [System.Speech.AudioFormat.AudioBitsPerSample]::Sixteen, [System.Speech.AudioFormat.AudioChannel]::Mono)",
    "$s.SetOutputToWaveFile($env:SYNAPSE_TTS_OUT, $f)",
    "$s.Speak($env:SYNAPSE_TTS_TEXT)",
    "$s.Dispose()",
  ].join("; ");
  const r = spawnSync("powershell.exe", ["-NoProfile", "-NonInteractive", "-Command", script], { env: { ...process.env, SYNAPSE_TTS_OUT: out, SYNAPSE_TTS_TEXT: text }, encoding: "utf8", timeout: 30_000 });
  try {
    if (r.status !== 0 || !fs.existsSync(out)) return null;
    return readWavPcm16k(fs.readFileSync(out));
  } finally {
    fs.rmSync(out, { force: true });
  }
}

/** parse a RIFF/WAVE (PCM 16-bit) and return 16 kHz mono int16 (linear resampling, channels averaged) */
export function readWavPcm16k(buf: Buffer): Int16Array {
  if (buf.toString("latin1", 0, 4) !== "RIFF" || buf.toString("latin1", 8, 12) !== "WAVE") throw new Error("not a WAV file");
  let pos = 12;
  let channels = 1;
  let rate = 16000;
  let bits = 16;
  let data: Buffer | null = null;
  while (pos + 8 <= buf.length) {
    const id = buf.toString("latin1", pos, pos + 4);
    const size = buf.readUInt32LE(pos + 4);
    const body = buf.subarray(pos + 8, Math.min(buf.length, pos + 8 + size));
    if (id === "fmt ") {
      channels = body.readUInt16LE(2);
      rate = body.readUInt32LE(4);
      bits = body.readUInt16LE(14);
    } else if (id === "data") {
      data = body;
      break;
    }
    pos += 8 + size + (size % 2);
  }
  if (!data) throw new Error("WAV has no data chunk");
  if (bits !== 16) throw new Error(`only 16-bit PCM WAV is supported (got ${bits}-bit)`);
  const n = Math.floor(data.length / 2 / channels);
  const mono = new Float32Array(n);
  for (let i = 0; i < n; i++) {
    let s = 0;
    for (let c = 0; c < channels; c++) s += data.readInt16LE((i * channels + c) * 2);
    mono[i] = s / channels;
  }
  if (rate === 16000) return Int16Array.from(mono, (v) => Math.round(v));
  const outLen = Math.floor((n * 16000) / rate);
  const out = new Int16Array(outLen);
  for (let i = 0; i < outLen; i++) {
    const x = (i * rate) / 16000;
    const i0 = Math.floor(x);
    const f = x - i0;
    out[i] = Math.round((mono[i0] ?? 0) * (1 - f) + (mono[Math.min(n - 1, i0 + 1)] ?? 0) * f);
  }
  return out;
}

/** a few seconds of a synthetic "voice-like" signal, used only when no speech could be synthesised */
function tone(): Int16Array {
  const out = new Int16Array(16000 * 2);
  for (let i = 0; i < out.length; i++) out[i] = Math.round(8000 * Math.sin((2 * Math.PI * 220 * i) / 16000) * (0.6 + 0.4 * Math.sin((2 * Math.PI * 3 * i) / 16000)));
  return out;
}

/** ask the running Synapse server for a Wispr client token over its WebSocket, exactly like the browser does */
function tokenFromSynapse(server: string, origin: string, code?: string): (opts?: { force?: boolean }) => Promise<WisprTokenInfo> {
  return (opts) =>
    new Promise<WisprTokenInfo>((resolve, reject) => {
      const ws = new (WebSocket as unknown as new (url: string, init?: { headers?: Record<string, string> }) => WebSocket)(server, { headers: { Origin: origin } });
      const timer = setTimeout(() => {
        ws.close();
        reject(new Error("the Synapse server did not answer the token request in 10 s"));
      }, 10_000);
      ws.onopen = () => ws.send(JSON.stringify({ type: "hello", deviceId: `wispr-check-${randomBytes(3).toString("hex")}`, kind: "desk", name: "wispr:check", ...(code ? { pairingCode: code } : {}) }));
      ws.onmessage = (ev) => {
        let m: { type?: string } & Record<string, unknown>;
        try {
          m = JSON.parse(String(ev.data));
        } catch {
          return;
        }
        if (m.type === "welcome") ws.send(JSON.stringify({ type: "wispr.token.request", ...(opts?.force ? { force: true } : {}) }));
        else if (m.type === "auth.required") {
          clearTimeout(timer);
          ws.close();
          reject(new Error(`the server wants a pairing code (${String(m.reason)}): rerun with --code <6 digits> (shown in the server console)`));
        } else if (m.type === "wispr.token") {
          clearTimeout(timer);
          ws.close();
          resolve({ mode: m.mode as WisprTokenInfo["mode"], ...(m.token ? { token: String(m.token) } : {}), ...(m.expiresAt ? { expiresAt: Number(m.expiresAt) } : {}), ...(m.wsUrl ? { wsUrl: String(m.wsUrl) } : {}), ...(m.restUrl ? { restUrl: String(m.restUrl) } : {}), ...(m.error ? { error: String(m.error) } : {}), ...(m.note ? { note: String(m.note) } : {}) });
        }
      };
      ws.onerror = () => {
        clearTimeout(timer);
        reject(new Error(`could not reach the Synapse server at ${server}. Start it with: pnpm dev:server`));
      };
    });
}

async function main(): Promise<number> {
  const a = parseArgs(process.argv.slice(2));
  const log = (s: string): void => console.log(s);

  // 0. the server must be using a speech engine (Wispr, or the on-device one: WISPR_MODE=local), otherwise there is nothing to check
  const httpBase = a.server.replace(/^ws/, "http").replace(/\/ws$/, "");
  try {
    const h = (await (await fetch(`${httpBase}/api/health`)).json()) as { modes?: { wispr?: string } };
    if (h.modes?.wispr !== "client" && h.modes?.wispr !== "local") {
      log(`The Synapse server is running with WISPR_MODE=${h.modes?.wispr ?? "?"}.\nPut WISPR_API_KEY=<your key> and WISPR_MODE=client in D:\\goa-hack\\.env, restart the server (pnpm dev:server), then run this again.`);
      return 2;
    }
  } catch {
    log(`Cannot reach the Synapse server at ${httpBase}. Start it first: pnpm dev:server`);
    return 2;
  }

  // 1. audio
  let pcm: Int16Array;
  let spoken: string | undefined;
  if (a.wav) {
    pcm = readWavPcm16k(fs.readFileSync(a.wav));
    log(`using ${a.wav}: ${(pcm.length / 16000).toFixed(1)} s`);
  } else {
    const s = synthesize(a.text);
    if (s) {
      pcm = s;
      spoken = a.text;
      log(`synthesised ${(pcm.length / 16000).toFixed(1)} s of speech with the Windows voice: "${a.text}"`);
    } else {
      pcm = tone();
      log("could not synthesise speech here (not Windows, or SAPI unavailable): sending a tone instead. The protocol checks still run, but expect an empty transcript. Pass --wav yourself.wav for a real test.");
    }
  }

  // 2. sockets that look like the browser's (Origin header)
  const createSocket: WsFactory = (url) =>
    new (WebSocket as unknown as new (u: string, init?: { headers?: Record<string, string> }) => WebSocket)(url, { headers: { Origin: a.origin } }) as unknown as WsLike;

  const report = await runWisprCheck({
    getToken: tokenFromSynapse(a.server, a.origin, a.code),
    origin: httpBase, // the on-device engine hands out relative endpoints: they resolve to the server itself
    pcm,
    ...(spoken ? { expect: spoken } : {}),
    pace: a.pace,
    packetFormat: a.packets,
    forceRest: a.rest,
    silence: a.silence,
    idleSecs: a.idle,
    language: a.language,
    createSocket,
    log,
  });
  console.log("\n" + renderReport(report));
  return report.ok ? 0 : 1;
}

// run only when executed directly (the module is also imported by tests)
if (process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]).replace(/\\/g, "/"))) {
  main()
    .then((code) => {
      process.exitCode = code;
    })
    .catch((e) => {
      console.error(String((e as Error).message ?? e));
      process.exitCode = 1;
    });
}
